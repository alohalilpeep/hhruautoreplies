"""Дописать в шапку выгруженного файла вопросов правила оформления ответов.

    python scripts/questions_note.py <файл> [<файл> …]

Файлы отвечаются нейросетью. Она охотно копирует один и тот же ответ на похожие
вопросы (одинаковые ответы у разных работодателей выглядят как шаблон, 16.10.2026)
и пишет как в документе — с заглавной буквы и точкой в конце, а в анкете так
никто не пишет (19.10.2026). Блок вставляется перед «ЧАСТЬ 1»; старая версия
блока заменяется новой, повторно блок не добавляется.
"""
import re
import sys
from pathlib import Path

MARK = "# КАК ОТВЕЧАТЬ НА ВОПРОСЫ"
OLD_MARKS = ("# КАК ОТВЕЧАТЬ НА ПОВТОРЯЮЩИЕСЯ ВОПРОСЫ",)
NOTE = f"""{MARK}:
#   Пиши ответы с маленькой буквы и не ставь точку в конце ответа.
#   Если вопрос по смыслу повторяет другой — в этом файле или уже отвеченный
#   раньше, — НЕ копируй ответ слово в слово. Перескажи те же факты другими
#   словами: другое начало, другой порядок, другие формулировки и длина фраз.
#   Факты (стаж, стек, цифры, проекты, контакты) не меняй и не выдумывай новых.
#   Одинаковые ответы у разных работодателей выглядят как шаблон.


"""
ANCHOR = "# " + "=" * 70 + "\n# ЧАСТЬ 1."
# блок правил: строка-заголовок, строки «#   …», затем пустые строки
BLOCK_RE = re.compile(r"^(?:" + "|".join(re.escape(m) for m in (MARK,) + OLD_MARKS)
                      + r"):\n(?:#   .*\n)*\n*", re.M)


def add_note(path):
    text = path.read_text(encoding="utf-8")
    if NOTE in text:
        return False
    text = BLOCK_RE.sub("", text)                  # старая версия блока — долой
    i = text.find(ANCHOR)
    if i < 0:                                      # шапка другого вида — в самое начало
        i = 0
    path.write_text(text[:i] + NOTE + text[i:], encoding="utf-8")
    return True


if __name__ == "__main__":
    for p in sys.argv[1:]:
        if add_note(Path(p)):
            print(f"  правила ответов добавлены в {Path(p).name}")
