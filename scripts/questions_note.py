"""Дописать в шапку выгруженного файла вопросов правило про повторяющиеся вопросы.

    python scripts/questions_note.py <файл> [<файл> …]

Файлы отвечаются нейросетью, а она охотно копирует один и тот же ответ на похожие
вопросы. Одинаковые ответы у разных работодателей выглядят как шаблон, поэтому
просим пересказывать (16.10.2026). Блок вставляется перед «ЧАСТЬ 1», один раз.
"""
import sys
from pathlib import Path

MARK = "# КАК ОТВЕЧАТЬ НА ПОВТОРЯЮЩИЕСЯ ВОПРОСЫ"
NOTE = f"""{MARK}:
#   Если вопрос по смыслу повторяет другой — в этом файле или уже отвеченный
#   раньше, — НЕ копируй ответ слово в слово. Перескажи те же факты другими
#   словами: другое начало, другой порядок, другие формулировки и длина фраз.
#   Факты (стаж, стек, цифры, проекты, контакты) не меняй и не выдумывай новых.
#   Одинаковые ответы у разных работодателей выглядят как шаблон.


"""
ANCHOR = "# " + "=" * 70 + "\n# ЧАСТЬ 1."


def add_note(path):
    text = path.read_text(encoding="utf-8")
    if MARK in text:
        return False
    i = text.find(ANCHOR)
    if i < 0:                                      # шапка другого вида — в самое начало
        i = 0
    path.write_text(text[:i] + NOTE + text[i:], encoding="utf-8")
    return True


if __name__ == "__main__":
    for p in sys.argv[1:]:
        if add_note(Path(p)):
            print(f"  правило про повторы добавлено в {Path(p).name}")
